import asyncio
import httpx

SEM = asyncio.Semaphore(10)

async def fetch_page(client, url):
    async with SEM:
        response = await client.get(url, timeout=20)

        response.raise_for_status()

        return url, response.text

async def fetch_all_pages(urls):

    async with httpx.AsyncClient(
        headers={"User-Agent": "Mozilla/5.0"}
    ) as client:

        tasks = [
            fetch_page(client, url)
            for url in urls
        ]

        results = await asyncio.gather(*tasks)

    return results

page_results = await fetch_all_pages(page_urls)

print("Pages downloaded:", len(page_results))

all_books = []

for page_url, html in page_results:
    books = extract_books(html, page_url)
    all_books.extend(books)

print("Total books:", len(all_books))

import pandas as pd

df = pd.DataFrame(all_books)

print(df.head())
