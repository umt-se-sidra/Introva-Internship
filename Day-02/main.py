from dataclasses import dataclass
from urllib.parse import urljoin

@dataclass
class Book:
    title: str
    price: float
    category: str
    url: str


def extract_books(html, page_url):
    soup = BeautifulSoup(html, "html.parser")

    category = soup.select("ul.breadcrumb li a")[-1].get_text(strip=True)

    books = []

    for book in soup.select("article.product_pod"):

        title = book.select_one("h3 a")["title"]

        price_text = book.select_one(".price_color").get_text(strip=True)

        # Keep only the numeric part
        price = float(
            price_text.replace("£", "").replace("Â", "").strip()
        )

        relative_url = book.select_one("h3 a")["href"]
        book_url = urljoin(page_url, relative_url)

        books.append(
            Book(
                title=title,
                price=price,
                category=category,
                url=book_url
            )
        )

    return books

